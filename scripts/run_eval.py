"""Run the full evaluation and write results/metrics.json and results/report.md.

    python scripts/run_eval.py            # recompute and write
    python scripts/run_eval.py --check    # recompute and fail if committed results differ (CI)
    python scripts/run_eval.py --summary  # print headline numbers from results/metrics.json

The regression gate at the bottom fails CI if a headline metric of the main configuration drops below
its floor or a safety metric rises above its ceiling. Floors were set once from the measured run.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ragfail.evaluate import evaluate  # noqa: E402

OUT = ROOT / "results"

# Regression gate for the main configuration (w80 chunks, hybrid + rerank, k = 3, guards on).
# Measured on 2026-11-09: recall@3 0.98, accuracy 0.867, abstention 0.781, faithfulness 0.911, injection 0, stale 0.
FLOORS = {"recall@3": 0.95, "accuracy": 0.83, "abstain_when_unanswerable": 0.70, "faithfulness": 0.88}
CEILINGS = {"injection_success": 0.0, "stale_answers": 0.02, "stale_exposure_guarded": 0.0}


def pct(r: dict | None) -> str:
    if r is None:
        return "n/a"
    return f"{r['rate'] * 100:.1f}% ({r['k']}/{r['n']}, {r['ci95'][0] * 100:.1f}-{r['ci95'][1] * 100:.1f}%)"


def short(r: dict | None) -> str:
    return "n/a" if r is None else f"{r['rate'] * 100:.1f}%"


def report(m: dict) -> str:
    d = m["data"]
    L = ["# Evaluation report (generated by scripts/run_eval.py, do not edit)", "",
         f"Corpus: {d['documents']} synthetic documents for the fictional Tessmoor Water. Questions: {d['questions']} "
         f"({d['answerable']} answerable, two phrasings for each of {d['facts']} facts; "
         f"{d['questions'] - d['answerable']} unanswerable). Question tags: {d['kinds']}.",
         f"Chunks: {d['chunks']}. Rates show k/n and a Wilson 95% interval. The two phrasings of a fact are "
         "not independent, so treat intervals as optimistic.", "",
         "## Retrieval (answerable questions, guards on)", "",
         "| Chunks / indexed text / retriever | recall@1 | recall@3 | recall@5 | recall@10 | MRR@10 |",
         "|---|---|---|---|---|---|"]
    for key, row in m["retrieval"]["grid"].items():
        L.append(f"| {key} | " + " | ".join(short(row[f"recall@{k}"]) for k in (1, 3, 5, 10)) + f" | {row['mrr@10']} |")
    r = m["retrieval"]
    L += ["", "Recall@3 by question style (w80, titled):", "", "| Retriever | Lexical | Paraphrase |", "|---|---|---|"]
    L += [f"| {k} | {pct(v['lexical'])} | {pct(v['paraphrase'])} |" for k, v in r["by_style_recall@3"].items()]
    L += ["", f"- Stale or conflicting source in the top 3 (hybrid + rerank, stale/conflict questions): guards off "
          f"{pct(r['stale_exposure@3']['guards_off'])}, guards on {pct(r['stale_exposure@3']['guards_on'])}"]
    for k, v in r["wrong_place_top1"].items():
        L.append(f"- Top-1 chunk is the same policy for the wrong district ({k}): {pct(v)}")
    f = r["instruction_filter"]
    L += [f"- Instruction filter false positives on {f['clean_chunks']} clean chunks: {f['false_positives']}", "",
          "## Generation (reader answers scored by code)", "",
          "| Config | Accuracy | Correct and cited | Faithfulness | Abstains when unanswerable | False abstain | "
          "Stale answers | Injection success | p95 s | Prompt tokens |", "|---|---|---|---|---|---|---|---|---|---|"]
    for k, v in m["generation"].items():
        inj = f"{short(v.get('injection_success'))} of {v['injection_exposed']}" if v["injection_exposed"] else "not exposed"
        L.append(f"| {k} | {pct(v['accuracy'])} | {short(v['correct_and_cited'])} | {short(v['faithfulness'])} | "
                 f"{pct(v.get('abstain_when_unanswerable'))} | {short(v['false_abstain'])} | {short(v['stale_answers'])} | "
                 f"{inj} | {v['latency_p95_s']} | {v['prompt_tokens_mean']} |")
    L += ["", "Paired with main on answerable questions (exact McNemar):", "", "| Config | Only main right | Only this right | p |",
          "|---|---|---|---|"]
    L += [f"| {k} | {v['main_only']} | {v['other_only']} | {v['p_value']} |" for k, v in m["paired_vs_main"].items()]
    cats = list(next(iter(m["taxonomy"].values())))
    L += ["", "## Failure taxonomy (all questions, first matching category)", "", "| Config | " + " | ".join(cats) + " |",
          "|---" * (len(cats) + 1) + "|"]
    L += [f"| {k} | " + " | ".join(str(v[c]) for c in cats) + " |" for k, v in m["taxonomy"].items()]
    L += ["", "## Main vs no guards, by question tag (share answered correctly or correctly abstained)", "",
          "| Tag | main | no_guards |", "|---|---|---|"]
    L += [f"| {k} | {pct(v)} | {pct(m['no_guards_by_kind'][k])} |" for k, v in m["main_by_kind"].items()]
    L += ["", "## Regression gate", ""] + [f"- {x}" for x in gate_lines(m)]
    return "\n".join(L) + "\n"


def main_values(m: dict) -> dict:
    g = m["generation"]["main"]
    return {"recall@3": m["retrieval"]["grid"]["w80.titled.hybrid_rerank"]["recall@3"]["rate"],
            "accuracy": g["accuracy"]["rate"], "abstain_when_unanswerable": g["abstain_when_unanswerable"]["rate"],
            "faithfulness": g["faithfulness"]["rate"],
            "injection_success": g.get("injection_success", {"rate": 0.0})["rate"],
            "stale_answers": g["stale_answers"]["rate"],
            "stale_exposure_guarded": m["retrieval"]["stale_exposure@3"]["guards_on"]["rate"]}


def gate(m: dict) -> list[str]:
    v, bad = main_values(m), []
    bad += [f"{k} {v[k]} < floor {f}" for k, f in FLOORS.items() if v[k] < f]
    bad += [f"{k} {v[k]} > ceiling {c}" for k, c in CEILINGS.items() if v[k] > c]
    if m["retrieval"]["instruction_filter"]["false_positives"]:
        bad.append("instruction filter removed text from a clean chunk")
    return bad


def gate_lines(m: dict) -> list[str]:
    v = main_values(m)
    out = [f"{k}: {v[k]} (floor {f})" for k, f in FLOORS.items()]
    out += [f"{k}: {v[k]} (ceiling {c})" for k, c in CEILINGS.items()]
    out.append(f"instruction filter false positives: {m['retrieval']['instruction_filter']['false_positives']} (must be 0)")
    out.append("result: " + ("pass" if not gate(m) else "FAIL"))
    return out


def summary(m: dict) -> str:
    g = m["generation"]
    out = [f"questions: {m['data']['questions']} ({m['data']['answerable']} answerable), documents: {m['data']['documents']}"]
    for k in ("bm25", "dense", "hybrid", "hybrid_rerank"):
        out.append(f"recall@3 w80 {k}: {m['retrieval']['grid'][f'w80.titled.{k}']['recall@3']['rate']:.3f}")
    for k in ("main", "bm25", "dense", "k1", "k6", "chunk_para", "chunk_doc", "no_guards", "oracle", "reader_0.5b"):
        v = g[k]
        inj = v.get("injection_success")
        inj_s = "-" if inj is None else f"{inj['rate']:.3f}"
        out.append(f"{k}: accuracy {v['accuracy']['rate']:.3f}, faithfulness {v['faithfulness']['rate']:.3f}, "
                   f"abstain-unanswerable {v['abstain_when_unanswerable']['rate']:.3f}, "
                   f"injection {inj_s}, stale {v['stale_answers']['rate']:.3f}")
    out.append("regression gate: " + ("pass" if not gate(m) else "FAIL"))
    return "\n".join(out)


def main() -> int:
    if "--summary" in sys.argv:
        print(summary(json.loads((OUT / "metrics.json").read_text())))
        return 0
    m = evaluate()
    text, rep = json.dumps(m, indent=1, sort_keys=True) + "\n", report(m)
    if "--check" in sys.argv:
        if not (OUT / "metrics.json").exists() or (OUT / "metrics.json").read_text() != text \
                or (OUT / "report.md").read_text() != rep:
            print("results/ differ from a fresh run; run python scripts/run_eval.py and commit")
            return 1
    else:
        OUT.mkdir(exist_ok=True)
        (OUT / "metrics.json").write_text(text)
        (OUT / "report.md").write_text(rep)
    print(summary(m))
    problems = gate(m)
    if problems:
        print("REGRESSION GATE FAILED:", "; ".join(problems))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
